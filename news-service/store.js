export async function readNews(env) {
  const stored = await env.JOBS.get(NEWS_KEY, 'json')
  if (Array.isArray(stored) && stored.length) {
    return stored.map((item) => ({ status: 'approved', ...item }))
  }
  return defaultNews
}

export async function writeNews(env, news) {
  await env.JOBS.put(NEWS_KEY, JSON.stringify(news))
}

// Картинки храним отдельными ключами KV, чтобы JSON новостей оставался лёгким.
export async function putImage(env, id, bytes, contentType = 'image/jpeg') {
  await env.JOBS.put(`${IMG_PREFIX}${id}`, bytes, { metadata: { contentType } })
}

export async function getImage(env, id) {
  const { value, metadata } = await env.JOBS.getWithMetadata(`${IMG_PREFIX}${id}`, 'arrayBuffer')
  if (!value) return null
  return { bytes: value, contentType: metadata?.contentType || 'image/jpeg' }
}

export async function delImage(env, id) {
  await env.JOBS.delete(`${IMG_PREFIX}${id}`)
}

// id картинки из её URL (хвост /api/news/image/<id>); '' если это не наша картинка.
export function imageIdFromUrl(url) {
  const m = String(url || '').match(/\/api\/news\/image\/([^/?#]+)/)
  return m ? m[1] : ''
}
